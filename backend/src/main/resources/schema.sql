CREATE TABLE IF NOT EXISTS memories (
 id VARCHAR(80) PRIMARY KEY,
 title VARCHAR(160) NOT NULL,
 kind VARCHAR(24) NOT NULL,
 occurred_on VARCHAR(10),
 content CLOB NOT NULL,
 summary CLOB NOT NULL,
 pinned BOOLEAN NOT NULL DEFAULT FALSE,
 status VARCHAR(16) NOT NULL,
 revision BIGINT NOT NULL DEFAULT 1,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 recalled_at BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS traits (
 id VARCHAR(80) PRIMARY KEY,
 memory_id VARCHAR(80) NOT NULL REFERENCES memories(id) ON DELETE CASCADE,
 description VARCHAR(300) NOT NULL,
 basis VARCHAR(16) NOT NULL,
 evidence VARCHAR(500) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'CANDIDATE'
);
CREATE INDEX IF NOT EXISTS traits_memory ON traits(memory_id);
CREATE TABLE IF NOT EXISTS chat_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id VARCHAR(80) NOT NULL,
 role VARCHAR(16) NOT NULL,
 content CLOB NOT NULL
);
CREATE INDEX IF NOT EXISTS chat_session ON chat_messages(session_id, id);
